import {network,artifacts} from 'hardhat';
import {BrowserProvider,Wallet,ContractFactory,Contract,ZeroAddress,parseEther,formatUnits} from 'ethers';
import {createRequire} from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
const Factory=require('@uniswap/v2-core/build/UniswapV2Factory.json');
const Pair=require('@uniswap/v2-core/build/UniswapV2Pair.json');
const wrapper=JSON.parse(fs.readFileSync(new URL('../../../contracts/WrappedNano.json',import.meta.url),'utf8'));
const connection=await network.create('nano');const provider=new BrowserProvider(connection.provider);provider.pollingInterval=100;
const alice=new Wallet('0x'+'1'.padStart(64,'0'),provider),bob=new Wallet('0x'+'2'.padStart(64,'0'),provider);
const deploy=async(artifact:any,args:any[]=[])=>{const contract=await new ContractFactory(artifact.abi,artifact.bytecode,alice).deploy(...args);await contract.waitForDeployment();return contract;};
const wn=await deploy(wrapper),quote=await deploy(await artifacts.readArtifact('PoolQuoteToken'));
// The local fixture permanently disables protocol-fee administration.
const factory=await deploy(Factory,[ZeroAddress]);
await (await factory.createPair(await wn.getAddress(),await quote.getAddress())).wait();
const pairAddress=await factory.getPair(await wn.getAddress(),await quote.getAddress());
const pair=new Contract(pairAddress,Pair.abi,alice);const wnFirst=(await pair.token0()).toLowerCase()===(await wn.getAddress()).toLowerCase();
const reserves=async()=>{const r=await pair.getReserves();return wnFirst?[r[0],r[1]]:[r[1],r[0]];};
const coherent=async()=>{const [w,q]=await reserves();assert.equal(await wn.balanceOf(pairAddress),w);assert.equal(await quote.balanceOf(pairAddress),q);};
await (await wn.deposit({value:parseEther('100')})).wait();
await (await wn.transfer(pairAddress,parseEther('100'))).wait();
await (await quote.transfer(pairAddress,1000n*10n**6n)).wait();
await (await pair.mint(alice.address)).wait();await coherent();
const initial=await reserves();assert.equal(initial[0],parseEther('100'));assert.equal(initial[1],1000n*10n**6n);
assert.equal(await pair.balanceOf(ZeroAddress),1000n);assert((await pair.balanceOf(alice.address))>0n);
const initialPrice=formatUnits(initial[1]*10n**18n/initial[0],6);assert.equal(initialPrice,'10.0');
await (await quote.transfer(bob.address,100n*10n**6n)).wait();
const trader=new Contract(pairAddress,Pair.abi,bob);
// A real reverted transaction, not just a failed gas estimate.
await assert.rejects(async()=>await (await trader.swap(wnFirst?1n:0n,wnFirst?0n:1n,bob.address,'0x',{gasLimit:500000})).wait());
assert.deepEqual(await reserves(),initial);assert.equal(await wn.balanceOf(bob.address),0n);await coherent();
const amountIn=10n*10n**6n,amountOut=amountIn*997n*initial[0]/(initial[1]*1000n+amountIn*997n);
await (await (quote.connect(bob) as any).transfer(pairAddress,amountIn)).wait();
await (await trader.swap(wnFirst?amountOut:0n,wnFirst?0n:amountOut,bob.address,'0x')).wait();
assert.equal(await wn.balanceOf(bob.address),amountOut);await coherent();const after=await reserves();
assert.equal(after[0],initial[0]-amountOut);assert.equal(after[1],initial[1]+amountIn);assert(after[0]*after[1]>=initial[0]*initial[1]);
const priceAfter=formatUnits(after[1]*10n**18n/after[0],6);assert(after[1]*initial[0]>initial[1]*after[0]);
await (await (wn.connect(bob) as any).withdraw(amountOut)).wait();assert.equal(await wn.balanceOf(bob.address),0n);
const liquidity=await pair.balanceOf(alice.address),supply=await pair.totalSupply();
const expectedW=liquidity*after[0]/supply,expectedQ=liquidity*after[1]/supply;
const beforeW=await wn.balanceOf(alice.address),beforeQ=await quote.balanceOf(alice.address);
await (await pair.transfer(pairAddress,liquidity)).wait();await (await pair.burn(alice.address)).wait();
assert.equal(await wn.balanceOf(alice.address)-beforeW,expectedW);assert.equal(await quote.balanceOf(alice.address)-beforeQ,expectedQ);assert.equal(await pair.totalSupply(),1000n);await coherent();
assert(BigInt(await provider.send('eth_getBalance',[await wn.getAddress(),'latest']))>=await wn.totalSupply());
const blocks=await provider.send('nano_networkBlocks',['0x0']);assert(blocks.blocks.every((b:any)=>b.bftCertificate?.votes.length>0));
console.log(JSON.stringify({protocol:'Uniswap V2 core 1.0.1',network:'temporary Nano Shanghai',pair:'WNANO/TESTQ',initialPrice,priceAfter,priceUnit:'TESTQ per NANO; synthetic asset, no monetary valuation',unpaidSwapRejected:true,liquidityWithdrawalVerified:true,certifiedBlocks:true}));
await connection.close();
