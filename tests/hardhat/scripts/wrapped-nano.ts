import {network, artifacts} from 'hardhat';
import {BrowserProvider, Wallet, ContractFactory, Contract, parseEther} from 'ethers';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const connection=await network.create('nano');
const provider=new BrowserProvider(connection.provider);provider.pollingInterval=100;
const alice=new Wallet('0x'+'1'.padStart(64,'0'),provider),bob=new Wallet('0x'+'2'.padStart(64,'0'),provider);
const artifact=JSON.parse(fs.readFileSync(new URL('../../../contracts/WrappedNano.json',import.meta.url),'utf8'));
const token=await new ContractFactory(artifact.abi,artifact.bytecode,alice).deploy();await token.waitForDeployment();
const address=await token.getAddress();const other=new Contract(address,artifact.abi,bob);
const balance=async()=>BigInt(await provider.send('eth_getBalance',[address,'latest']));
const backed=async()=>assert((await balance())>=await token.totalSupply());
await (await token.deposit({value:parseEther('1')})).wait();
assert.equal(await token.balanceOf(alice.address),parseEther('1'));await backed();
await (await alice.sendTransaction({to:address,value:parseEther('0.2')})).wait();
assert.equal(await token.totalSupply(),parseEther('1.2'));
await (await token.transfer(bob.address,parseEther('0.4'))).wait();
await assert.rejects(other.transferFrom(alice.address,bob.address,1));
await (await other.withdraw(parseEther('0.2'))).wait();
assert.equal(await token.balanceOf(bob.address),parseEther('0.2'));assert.equal(await balance(),parseEther('1'));await backed();
await assert.rejects(other.withdraw(parseEther('0.3')));
const receiverArtifact=await artifacts.readArtifact('WrappedNanoReceiver');
const receiver=await new ContractFactory(receiverArtifact.abi,receiverArtifact.bytecode,alice).deploy(address);await receiver.waitForDeployment();
await (await receiver.deposit({value:parseEther('0.1')})).wait();
await (await receiver.configure(true,false)).wait();
const supply=await token.totalSupply(),collateral=await balance(),held=await token.balanceOf(await receiver.getAddress());
// Explicit gas forces execution and a failed receipt rather than estimate-only rejection.
await assert.rejects(async()=>await (await receiver.withdraw(held,{gasLimit:200000})).wait());
assert.equal(await token.totalSupply(),supply);assert.equal(await balance(),collateral);assert.equal(await token.balanceOf(await receiver.getAddress()),held);
await (await receiver.configure(false,true)).wait();
await (await receiver.withdraw(held,{gasLimit:200000})).wait();
assert.equal(await receiver.reentrySucceeded(),false);assert.equal(await token.balanceOf(await receiver.getAddress()),0n);await backed();
assert.equal(await receiver.reentryAttempts(),1n);
await (await token.approve(bob.address,parseEther('0.1'))).wait();
await (await other.transferFrom(alice.address,bob.address,parseEther('0.1'))).wait();
assert.equal(await token.allowance(alice.address,bob.address),0n);await backed();
await (await other.withdraw(await token.balanceOf(bob.address))).wait();
await (await token.withdraw(await token.balanceOf(alice.address))).wait();
assert.equal(await token.totalSupply(),0n);assert.equal(await balance(),0n);
const blocks=await provider.send('nano_networkBlocks',['0x0']);assert(blocks.blocks.every((block:any)=>block.bftCertificate?.votes.length>0));
console.log(JSON.stringify({contract:'WrappedNano',nativeClient:await provider.send('web3_clientVersion',[]),collateralized:true,rejectedRefundRolledBack:true,reentryRejected:true,fullRedemption:true,certifiedBlocks:true}));
await connection.close();
