import {readFileSync} from 'node:fs';
import {resolve} from 'node:path';
import assert from 'node:assert/strict';
const text=readFileSync(resolve(process.argv[2],'tests-full.log'),'utf8');
assert.equal((text.match(/Test Passed\./g)||[]).length,3);
for(const name of ['consensus_committee_participation','ethereum_consensus_attestation_root','consensus_attestation_conflicts'])assert(text.includes(`Testing: ${name}\n`));
const rows=text.split('\n').filter(l=>l.startsWith('{')).map(l=>JSON.parse(l));assert.equal(rows.length,3);
const r=rows.find(r=>r.scenario==='attestation-conflicts');assert(r);assert.equal(r.cases,24);assert.equal(r.signaturesAuthenticated,false);assert.equal(r.penaltiesApplied,false);
assert.equal(rows.find(r=>r.scenario==='consensus-attestation-root').officialCases,5);
assert.equal(rows.find(r=>r.scenario==='consensus-committee-participation').rejected,27);
console.log(JSON.stringify({verified:true,...r},null,2));
