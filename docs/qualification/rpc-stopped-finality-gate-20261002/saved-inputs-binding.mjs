import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
import {stoppedReceipt,restoreAuditRequest} from '/tmp/nano-rpc-wan-harness-candidate-20261002/tests/multihost/restore-config.mjs';
const root='/Users/boris/Dev/blockchain-nano';
const meta=JSON.parse(await readFile('/tmp/nano-surviving-full-fixture-independent-inputs-20261002.json','utf8'));
const text=await readFile(root+'/'+meta.receiptFile,'utf8');
const configuration=await readFile(meta.originalConfigurationPath,'utf8');
const hash=text=>createHash('sha256').update(text).digest('hex');
assert.equal(hash(text),meta.receiptLogSha256);
assert.equal(hash(configuration),meta.originalConfigurationSha256);
const receipt=stoppedReceipt(text),request=restoreAuditRequest(JSON.parse(configuration),receipt);
const qualified=JSON.parse(await readFile(root+'/docs/qualification/rpc-native-offline-control-20261002/positive-current.json','utf8'));
assert.deepEqual(request.expectedCheckpoint,qualified.expectedCheckpoint);
assert.deepEqual(request.requiredFinalized,qualified.requiredFinalized);
assert.equal(request.profile.sha256,qualified.profile.sha256);
assert.equal(request.anchor.sha256,qualified.anchor.sha256);
assert.deepEqual(request.limits,qualified.limits);
